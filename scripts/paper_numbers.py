"""Five-year fact sheet for the paper (2022–2026): one markdown document with, per year, the origin-change / leak / withdrawal
event counts and test-split floors, the RPKI validity shares and floors by class (paper population = reason != rpki_invalid_sample,
and the label-free invalid stratum separately), the recovery pairing, the ROV frontier (live and frozen-series files where present)
and the per-year label-free stratum floors. Reads only eventset/<year>*/ outputs; prints markdown.
usage: paper_numbers.py [years...]  → docs/paper/five-year-numbers.md (redirect)"""
from __future__ import annotations

import json
import argparse
from pathlib import Path

import polars as pl

from bgbench import config

_ap = argparse.ArgumentParser()
_ap.add_argument("years", nargs="*", type=int)
_ap.add_argument("--recovery-tag", default="recovery", help="eventset suffix containing the paired measurements")
_a = _ap.parse_args()
YEARS = _a.years or [2022, 2023, 2024, 2025, 2026]
ES = config.DATA_ROOT / "eventset"


def j(path: Path):
    try:
        return json.loads(path.read_text())
    except Exception:
        return None


def enforcement_cell(shares: dict, key: str) -> str:
    value = shares.get(key, {}).get("share")
    return "–" if value is None else f"{value:.2f}"


def floors(d: Path, target="final_2h") -> dict[str, float]:
    f = d / "persistence_test.csv"
    if not f.exists():
        return {}
    try:
        t = pl.read_csv(f).filter(pl.col("target") == target)
    except pl.exceptions.NoDataError:
        return {}
    return {r["delta"]: round(r["jaccard_mean"], 3) for r in t.iter_rows(named=True)}


def fl(fd: dict, keys=("d30s", "d1m", "d5m", "d15m")) -> str:
    return " / ".join(f"{fd[k]:.2f}" if k in fd else "–" for k in keys)


def jac(a, b):
    return pl.col(a).list.set_intersection(pl.col(b)).list.len() / pl.col(a).list.set_union(pl.col(b)).list.len().clip(1)


print("# Five-year fact sheet (generated by scripts/paper_numbers.py)\n")
print("Floors are J(set_Δ, set_2h), test split, at 30 s / 1 / 5 / 15 min. Origin-change rows marked *paper* exclude the label-free "
      "stratum (reason rpki_invalid_sample); *label-free* rows are that stratum alone.\n")

print("## Event counts and pooled floors\n")
print("| year | set | events (ok) | train / test | floors 30 s / 1 / 5 / 15 min | t90 > 5 min |\n|---|---|---|---|---|---|")
for y in YEARS:
    for tag, name in (("", "origin change"), ("_leak", "route leak"), ("_withdrawal", "withdrawal wave")):
        d = ES / f"{y}{tag}"
        s = j(d / "summary.json")
        if not s:
            continue
        print(f"| {y} | {name} | {s['events']:,} | {s['train']:,} / {s['test']:,} | {fl(floors(d))} | {s.get('frac_events_t90_over_5min', '–')} |")

print("\n## Origin-change pooled floors by population (test split; paper = reason != rpki_invalid_sample)\n")
print("| year | population | events (ok) | train / test | J 30 s mean / median | 1 min | 5 min | 15 min | still growing at 30 s | extent p50 / p90 |\n|---|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / str(y)
    if not (d / "events.parquet").exists():
        continue
    ev = pl.read_parquet(d / "events.parquet").filter(pl.col("error").is_null()).with_columns(
        pl.when(pl.col("reason") == "rpki_invalid_sample").then(pl.lit("label-free invalid stratum")).otherwise(pl.lit("paper")).alias("pop"),
        *[jac(c, "set_final_2h").alias(c.replace("set_", "J_")) for c in ("set_d30s", "set_d1m", "set_d5m", "set_d15m")],
        (pl.col("set_d30s").list.len() < pl.col("set_final_2h").list.len()).alias("growing"))
    for pop in ("paper", "stratified sample only", "label-free invalid stratum"):
        g = ev.filter(pl.col("reason") == "stratified") if pop == "stratified sample only" else ev.filter(pl.col("pop") == pop)
        if not g.height:
            continue
        t = g.filter(pl.col("split") == "test")
        print(f"| {y} | {pop} | {g.height:,} | {(g['split'] == 'train').sum():,} / {t.height:,} | {t['J_d30s'].mean():.2f} / {t['J_d30s'].median():.2f} | {t['J_d1m'].mean():.2f} | "
              f"{t['J_d5m'].mean():.2f} | {t['J_d15m'].mean():.2f} | {t['growing'].mean():.0%} | {g['asns_final_2h'].median():.0f} / {g['asns_final_2h'].quantile(0.9):.0f} |")

print("\n## Origin changes by population and validity (test split)\n")
print("| year | population | class | test n | J 30 s | 1 min | 5 min | 15 min | extent p50 |\n|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / str(y)
    if not (d / "events.parquet").exists() or not (d / "rpki_validity.parquet").exists():
        continue
    ev = pl.read_parquet(d / "events.parquet").filter(pl.col("error").is_null() & (pl.col("split") == "test"))
    ev = ev.join(pl.read_parquet(d / "rpki_validity.parquet").select("event_id", "validity"), on="event_id", how="left")
    ev = ev.with_columns(pl.when(pl.col("reason") == "rpki_invalid_sample").then(pl.lit("label-free invalid stratum")).otherwise(pl.lit("paper")).alias("pop"),
                         *[jac(c, "set_final_2h").alias(c.replace("set_", "J_")) for c in ("set_d30s", "set_d1m", "set_d5m", "set_d15m")],
                         pl.col("set_final_2h").list.len().alias("extent"))
    t = (ev.group_by("pop", "validity").agg(n=pl.len(), J30=pl.col("J_d30s").mean(), J1=pl.col("J_d1m").mean(), J5=pl.col("J_d5m").mean(),
                                            J15=pl.col("J_d15m").mean(), ext=pl.col("extent").median()).sort("pop", "validity"))
    for r in t.iter_rows(named=True):
        print(f"| {y} | {r['pop']} | {r['validity']} | {r['n']:,} | {r['J30']:.3f} | {r['J1']:.3f} | {r['J5']:.3f} | {r['J15']:.3f} | {r['ext']:.0f} |")
    allp = ev.filter(pl.col("pop") == "paper")
    sh = allp.group_by("validity").agg(n=pl.len()).with_columns(share=(pl.col("n") / pl.col("n").sum()).round(3)).sort("validity")
    print(f"| {y} | paper | *shares of test events* | " + ", ".join(f"{r['validity']} {r['share']:.1%}" for r in sh.iter_rows(named=True)) + " | | | | | |")

print("\n## Recovery pairs, paper population (2022 full selection; 2023–2026 exclude invalid sampling stratum)\n")
print("| year | pairs | gap p50 | hijack J30 | recovery J30 | ΔJ30 [CI] | recovery slower | reach ratio p50 | return-path ASes absent from hijack paths | enforcing: R−H / R∩H / H−R |\n|---|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / f"{y}_{_a.recovery_tag}"
    suffix = "" if y == 2022 else "_labelled"
    p, o = j(d / f"pairs_summary{suffix}.json"), j(d / f"overlap_summary{suffix}.json")
    r = j(d / f"rov_summary{suffix}_frozen2505.json") or j(d / f"rov_summary{suffix}.json")
    if not p:
        continue
    dj = p["paired_j30_diff_recovery_minus_hijack"]
    dj["ci95"] = dj.get("ci95") or [float("nan"), float("nan")]
    es = r["enforcing_share"] if r else {}
    print(f"| {y} | {p['pairs']:,} | {p['gap_s_p50']:.0f} s | {p['hijack']['j30_mean']:.2f} | {p['recovery']['j30_mean']:.2f} | {dj['mean']:.2f} [{dj['ci95'][0]:.2f}, {dj['ci95'][1]:.2f}] | "
          f"{p['recovery_slower_t90_frac']:.0%} | {p['recovery_reach_over_hijack_reach_p50']:.2f}× | {o['recoverers_never_carried_hijack_mean']:.0%} | "
          f"{enforcement_cell(es, 'R-H')} / {enforcement_cell(es, 'R&H')} / {enforcement_cell(es, 'H-R')} |" if o else "")

print("\n## ROV frontier (mean log-odds frontier vs carriers, invalid / unknown / valid)\n")
print("| year | file | invalid n | invalid | unknown | valid | enforcing carriers (invalid) |\n|---|---|---|---|---|---|---|")
for y in YEARS:
    for f in sorted((ES / str(y)).glob("rov_frontier*.json")):
        if f.name not in ("rov_frontier.json", "rov_frontier_frozen2505.json", "rov_frontier_labelled.json", "rov_frontier_stratum.json", "rov_frontier_labelled_frozen2505.json", "rov_frontier_stratum_frozen2505.json"):
            continue
        r = j(f)
        if not r or "by_validity" not in r:
            continue
        b = r["by_validity"]
        def cell(v):
            if v not in b or b[v].get("log_odds_frontier_vs_carriers_mean") is None:
                return "–"
            ci = b[v].get("log_odds_mean_ci95_bootstrap") or [float("nan"), float("nan")]
            return f"{b[v]['log_odds_frontier_vs_carriers_mean']:+.2f} [{ci[0]:+.2f}, {ci[1]:+.2f}]"
        print(f"| {y} | {f.name} | {b.get('invalid', {}).get('events', '–')} | {cell('invalid')} | {cell('unknown')} | {cell('valid')} | {b.get('invalid', {}).get('enforcing_share_carriers', float('nan')):.3f} |")


print("\n## Validity table (all replayed events of the year, by population)\n")
print("| year | population | new origin | events (share) | catalogue-labelled | ASes at 2 h p50 / p90 | duration p50 | J 30 s test (n) | growing at 30 s |\n|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / str(y)
    if not (d / "events.parquet").exists() or not (d / "rpki_validity.parquet").exists():
        continue
    ev = pl.read_parquet(d / "events.parquet").filter(pl.col("error").is_null())
    ev = ev.join(pl.read_parquet(d / "rpki_validity.parquet").select("event_id", "validity", "prev_validity"), on="event_id", how="left")
    ev = ev.with_columns(pl.when(pl.col("reason") == "rpki_invalid_sample").then(pl.lit("label-free invalid stratum")).otherwise(pl.lit("paper")).alias("pop"),
                         jac("set_d30s", "set_final_2h").alias("J30"), (pl.col("set_d30s").list.len() < pl.col("set_final_2h").list.len()).alias("growing"))
    for pop in ("paper", "stratified sample only", "label-free invalid stratum"):
        g = ev.filter(pl.col("reason") == "stratified") if pop == "stratified sample only" else ev.filter(pl.col("pop") == pop)
        if not g.height:
            continue
        tot = g.height
        t = (g.group_by("validity").agg(n=pl.len(), lab=pl.col("labelled").mean(), r50=pl.col("asns_final_2h").median(), r90=pl.col("asns_final_2h").quantile(0.9),
                                        dur=pl.col("duration_min").median(), grow=pl.col("growing").mean(),
                                        J=pl.col("J30").filter(pl.col("split") == "test").mean(), nt=(pl.col("split") == "test").sum()).sort("validity"))
        for r in t.iter_rows(named=True):
            print(f"| {y} | {pop} | {r['validity']} | {r['n']:,} ({r['n']/tot:.1%}) | {r['lab']:.0%} | {r['r50']:.0f} / {r['r90']:.0f} | {r['dur']:.0f} min | {r['J']:.2f} ({r['nt']:,}) | {r['grow']:.0%} |")
    inv_valid = ev.filter((pl.col("pop") == "paper") & (pl.col("validity") == "invalid") & (pl.col("prev_validity") == "valid")).height
    inv_inv = ev.filter((pl.col("pop") == "paper") & (pl.col("validity") == "invalid") & (pl.col("prev_validity") == "invalid")).height
    print(f"| {y} | paper | *invalid displacing valid / invalid* | {inv_valid:,} / {inv_inv:,} | | | | | |")

print("\n## Recovery measurements, all unique return events before pair filtering\n")
print("| year | recoveries replayed (ok) | train / test | gap p50 | ASes in observed return paths p50 / p90 | t90 p50 / p90 | share t90 > 5 min | floors 30 s / 1 / 5 / 15 min | test median J30 |\n|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / f"{y}_{_a.recovery_tag}"
    if not (d / "events.parquet").exists():
        continue
    s_ = j(d / "summary.json") or {}
    e = pl.read_parquet(d / "events.parquet").filter(pl.col("error").is_null())
    p = j(d / "pairs_summary.json") or {}
    te = e.filter(pl.col("split") == "test").with_columns(jac("set_d30s", "set_final_2h").alias("J30"))
    print(f"| {y} | {e.height:,} | {s_.get('train', '–')} / {s_.get('test', '–')} | {p.get('gap_s_p50', float('nan')):.0f} s | {e['asns_final_2h'].median():.0f} / {e['asns_final_2h'].quantile(0.9):.0f} | "
          f"{e['t90_s'].median():.0f} s / {e['t90_s'].quantile(0.9):.0f} s | {(e['t90_s'] > 300).mean():.0%} | {fl(floors(d))} | {te['J30'].median():.2f} |")

print("\n## Recovery pairs by hijack population (files with suffix _labelled / _stratum where present)\n")
print("| year | population | pairs | hijack J30 | recovery J30 | ΔJ30 [CI] | recovery slower | reach ratio p50 | return-path ASes absent from hijack paths | enforcing R−H / R∩H / H−R (series) |\n|---|---|---|---|---|---|---|---|---|---|")
for y in YEARS:
    d = ES / f"{y}_{_a.recovery_tag}"
    for suf, pop in (("_labelled", "catalogue + stratified"), ("_stratum", "label-free invalid stratum"), ("", "all")):
        p, o = j(d / f"pairs_summary{suf}.json"), j(d / f"overlap_summary{suf}.json")
        if not p:
            continue
        r = j(d / f"rov_summary{suf}_frozen2505.json") or j(d / f"rov_summary{suf}.json")
        series = "frozen 2025-05" if r and r.get("freeze_date") else "live"
        if not r:
            r = j(d / f"rov_summary{suf}.json"); series = "live"
        es = (r or {}).get("enforcing_share", {})
        dj = p["paired_j30_diff_recovery_minus_hijack"]
        dj["ci95"] = dj.get("ci95") or [float("nan"), float("nan")]
        print(f"| {y} | {pop} | {p['pairs']:,} | {p['hijack']['j30_mean']:.2f} | {p['recovery']['j30_mean']:.2f} | {dj['mean']:.2f} [{dj['ci95'][0]:.2f}, {dj['ci95'][1]:.2f}] | "
              f"{p['recovery_slower_t90_frac']:.0%} | {p['recovery_reach_over_hijack_reach_p50']:.2f}× | {o['recoverers_never_carried_hijack_mean']:.0%} | "
              f"{enforcement_cell(es, 'R-H')} / {enforcement_cell(es, 'R&H')} / {enforcement_cell(es, 'H-R')} ({series}) |")

print("\n## Per-collector floors by class at 30 s (test split; per_vp_by_validity{_labelled}.json = paper population where present)\n")
print("| year | file | class | VPs | mean J at 30 s: min–max (std) | ordering invalid > unknown > valid holds at |\n|---|---|---|---|---|---|")
import statistics
for y in YEARS:
    for suf in ("_labelled", ""):
        r = j(ES / str(y) / f"per_vp_by_validity{suf}.json")
        if not r:
            continue
        rows = [x for x in r["per_vp_by_validity"] if x["delta"] == "d30s"]
        by = {}
        for x in rows:
            by.setdefault(x["validity"], {})[x["collector"]] = x["jaccard_mean"]
        cols = sorted(set.intersection(*[set(v) for v in by.values()])) if by else []
        holds = sum(1 for c in cols if by.get("invalid", {}).get(c, -1) > by.get("unknown", {}).get(c, -1) > by.get("valid", {}).get(c, -1))
        for cls in ("invalid", "unknown", "valid"):
            v = list(by.get(cls, {}).values())
            if v:
                print(f"| {y} | per_vp_by_validity{suf}.json | {cls} | {len(v)} | {min(v):.2f}–{max(v):.2f} ({statistics.pstdev(v):.3f}) | {holds} / {len(cols)} |")
        break

