        for b in beacons:
            cells = []
            for yy in years:
                v = [float(r["ratio_to_valid_p50"]) for r in rows if r["beacon"] == b and r["month"].startswith(yy)]
                cells.append(f"{statistics.median(v):.2f} ({len(v)} mo)" if v else "–")
